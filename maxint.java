public class maxint {
    public static void main(String[] args) {
        int maxInt = Integer.MAX_VALUE + 1;
        double a = 0.1;
        double b = 0.2;
        double c = a + b;
        System.out.println("The maximum integer value is: " + maxInt);
        System.out.println("The sum of a and b is: " + c);
    }
}